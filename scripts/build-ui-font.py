#!/usr/bin/env python3
"""Bake licensed sans-serif glyphs; normal PS5 builds need no font library."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
output = ['// Generated by scripts/build-ui-font.py; see vendor/vera/LICENSE.txt.',
          '#pragma once', '#include <cstdint>', 'namespace native::ui {',
          'struct Glyph { unsigned offset, count, advance; };',
          'struct Run { uint8_t x, y, width, alpha; };']
for size in (32, 40, 56, 96):
    font = ImageFont.truetype(str(root / 'homebrew/vendor/vera' / ('VeraBd.ttf' if size >= 56 else 'Vera.ttf')), size)
    runs, glyphs = [], []
    for code in range(32, 127):
        mask = Image.new('L', (128, 128))
        ImageDraw.Draw(mask).text((0, 0), chr(code), font=font, fill=255)
        offset = len(runs)
        # Quantized alpha runs reduce both asset size and draw-call overhead.
        for y in range(128):
            x = 0
            while x < 128:
                alpha = (mask.getpixel((x, y)) + 8) // 17 * 17
                end = x + 1
                while end < 128 and (mask.getpixel((end, y)) + 8) // 17 * 17 == alpha:
                    end += 1
                if alpha:
                    runs.append((x, y, end - x, min(alpha, 255)))
                x = end
        glyphs.append((offset, len(runs) - offset, round(font.getlength(chr(code)))))
    output.append(f'inline constexpr Run runs{size}[] = {{')
    output.extend('{' + ','.join(map(str, run)) + '},' for run in runs)
    output.append('};')
    output.append(f'inline constexpr Glyph glyphs{size}[] = {{')
    output.extend('{' + ','.join(map(str, glyph)) + '},' for glyph in glyphs)
    output.append('};')
output.append('}')
(root / 'homebrew/native-ui-font.hpp').write_text('\n'.join(output) + '\n')
